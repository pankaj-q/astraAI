import { useState } from "react";
import { X, ChevronDown, ChevronUp, FileText, Code2 } from "lucide-react";

const artifactTypes = {
  code: { icon: Code2, label: "Code", bg: "bg-[#1E1E2E]" },
  document: { icon: FileText, label: "Document", bg: "bg-[#1E1E2E]" },
  html: { icon: Code2, label: "HTML", bg: "bg-[#1E1E2E]" },
  markdown: { icon: FileText, label: "Markdown", bg: "bg-[#1E1E2E]" },
};

function ArtifactArea({ artifact, onClose }) {
  const [isExpanded, setIsExpanded] = useState(false);
  const [copied, setCopied] = useState(false);

  if (!artifact) return null;

  const type = artifactTypes[artifact.type] || artifactTypes.code;
  const Icon = type.icon;

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(artifact.content);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (err) {
      console.error("Failed to copy:", err);
    }
  };

  return (
    <div className="fixed bottom-0 right-0 w-full max-w-2xl h-[60vh] bg-[#15171A] border-l border-t border-[#24272C] shadow-2xl z-50 flex flex-col animate-slide-in">
      <div className="flex items-center justify-between px-4 py-3 border-b border-[#24272C] bg-[#111316]">
        <div className="flex items-center gap-3">
          <div className={`flex h-8 w-8 items-center justify-center rounded-lg ${type.bg} text-[#858A93]`}>
            <Icon size={16} strokeWidth={2} />
          </div>
          <div>
            <p className="text-sm font-medium text-[#E8E9EB]">{artifact.title || "Artifact"}</p>
            <p className="text-[11px] text-[#686D75] capitalize">{type.label}</p>
          </div>
        </div>
        <div className="flex items-center gap-2">
          <button
            onClick={handleCopy}
            aria-label="Copy to clipboard"
            className="flex h-8 w-8 items-center justify-center rounded-lg text-[#858A93] transition-colors hover:bg-[#25282E] hover:text-[#E8E9EB]"
            title={copied ? "Copied!" : "Copy to clipboard"}
          >
            {copied ? (
              <span className="text-[11px] font-medium text-[#22C55E]">Copied</span>
            ) : (
              <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
                <rect x="9" y="9" width="13" height="13" rx="2" ry="2" />
                <path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1" />
              </svg>
            )}
          </button>
          <button
            onClick={() => setIsExpanded(!isExpanded)}
            aria-label={isExpanded ? "Collapse" : "Expand"}
            className="flex h-8 w-8 items-center justify-center rounded-lg text-[#858A93] transition-colors hover:bg-[#25282E] hover:text-[#E8E9EB]"
          >
            {isExpanded ? <ChevronUp size={16} strokeWidth={2} /> : <ChevronDown size={16} strokeWidth={2} />}
          </button>
          <button
            onClick={onClose}
            aria-label="Close artifact"
            className="flex h-8 w-8 items-center justify-center rounded-lg text-[#858A93] transition-colors hover:bg-[#25282E] hover:text-[#E8E9EB]"
          >
            <X size={16} strokeWidth={2} />
          </button>
        </div>
      </div>

      <div className="flex-1 overflow-auto p-4">
        <pre className="text-sm leading-relaxed text-[#E8E9EB] whitespace-pre-wrap word-break-break-all font-mono">
          <code>{artifact.content}</code>
        </pre>
      </div>

      <div className="px-4 py-3 border-t border-[#24272C] bg-[#111316]">
        <p className="text-center text-[11px] text-[#686D75]">
          Artifact generated by AstraAI. Verify important information.
        </p>
      </div>
    </div>
  );
}

export default ArtifactArea;